import { posix } from 'node:path';
import { decodeNamedCharacterReference } from 'decode-named-character-reference';
import { parseSourceDocument } from '../plugins/source-document.mjs';

// Reviewed MDX: one import, one component with literal props, and Diataxis
// comments. No executable expressions, spread attributes, HTML, or other ESM.
const reviewedImport = "import ConfigReference from '../../../../components/ConfigReference.astro';";
const comments = /^\/\* Diataxis: (tutorial|how-to|reference|explanation)(; generated by sitedocs)? \*\/$/;
const declarationPackages = new Set(['admin', 'audit', 'audit/auditpg', 'audit/auditadmin', 'auth', 'auth/authbind', 'execution', 'execution/pgstore', 'execution/executionadmin', 'quota', 'quota/redisstore', 'quota/quotaadmin', 'quota/quotaotel', 'quota/quotaprom', 'quota/quotamcp', 'quota/quotastripe', 'quota/quotastripe/stripeadmin', 'tenant', 'webhook', 'webhook/webhookmem', 'webhook/webhookpg', 'webhook/webhookadmin']);
const markdownNodes = new Set(['root', 'yaml', 'paragraph', 'text', 'heading', 'thematicBreak', 'blockquote', 'list', 'listItem', 'emphasis', 'strong', 'delete', 'break', 'inlineCode', 'code', 'link', 'image', 'definition', 'linkReference', 'imageReference']);

export function checkDestination(name, input, files) {
  let destination = input.replace(/&(#x[0-9a-f]+|#\d+|[a-z][a-z0-9]+);/gi, (whole, entity) => {
    if (entity.startsWith('#')) {
      const value = entity[1].toLowerCase() === 'x' ? Number.parseInt(entity.slice(2), 16) : Number(entity.slice(1));
      return value <= 0x10ffff ? String.fromCodePoint(value) : whole;
    }
    return decodeNamedCharacterReference(entity) ?? whole;
  });
  for (let i = 0; i < 8; i++) {
    const decoded = decodeURIComponent(destination);
    if (decoded === destination) break;
    destination = decoded;
  }
  if (/[%\\\x00\r\n\t]/.test(destination)) throw new Error(`${name}: invalid reference`);
  const lower = destination.toLowerCase();
  // Check components before URL normalization can erase them with '..'.
  const path = lower.split(/[?#]/)[0];
  if (/(^|\/)(internal|private|\.tmp|fixtures?|\.env)(\/|$)/.test(path) || /(^|\/)docs\/.*\.md($|[?#])/.test(lower) || /\.sql($|[?#])/.test(lower) || /(?:github\.com|raw\.githubusercontent\.com)\/labstack\/echo-pro(?:[/?#]|$)/.test(lower)) {
    throw new Error(`${name}: Private reference`);
  }
  if (/^[a-z][a-z\d+.-]*:|^\/\//i.test(destination)) {
    const url = new URL(destination, 'https://echo.labstack.com');
    if (/(?:^|\.)(?:github\.com|githubusercontent\.com)$/.test(url.hostname.replace(/\.$/, '')) && posix.normalize(url.pathname).includes('/labstack/echo-pro')) throw new Error(`${name}: Private repository URL`);
    if (!['https:', 'http:'].includes(url.protocol) || url.username || url.password) throw new Error(`${name}: non-public URL`);
    return;
  }
  const target = destination.split(/[?#]/)[0];
  if (!target || posix.normalize(target).startsWith('/pro/') && !posix.extname(posix.normalize(target))) return;
  const resolved = posix.normalize(posix.join(posix.dirname(name), target));
  if (target.startsWith('/') || !files.has(resolved)) throw new Error(`${name}: file outside Pro bundle`);
}

export function checkMDX(name, content, files, api) {
  checkTextURLs(name, content, files);
  let tree;
  try { tree = parseSourceDocument(content, name); }
  catch { throw new Error(`${name}: invalid MDX syntax`); }
  let imported = false;
  function visit(node) {
    if (node.type === 'text' && /^(?:import|export)\b/m.test(node.value)) throw new Error(`${name}: unreviewed ESM text`);
    if (node.type === 'mdxjsEsm') {
      if (!name.startsWith('pages/reference/') || imported || node.value !== reviewedImport) throw new Error(`${name}: unreviewed MDX import or export`);
      imported = true;
    } else if (node.type === 'mdxFlowExpression' || node.type === 'mdxTextExpression') {
      if (!comments.test(node.value)) throw new Error(`${name}: MDX expressions are not allowed`);
    } else if (node.type === 'mdxJsxFlowElement' || node.type === 'mdxJsxTextElement') {
      const attributes = node.attributes;
      if (!imported || node.name !== 'ConfigReference' || node.children.length || attributes.length !== 2 || attributes.some((a) => a.type !== 'mdxJsxAttribute' || typeof a.value !== 'string') || attributes[0].name !== 'source' || attributes[0].value !== 'pro' || attributes[1].name !== 'name' || !api.configs.some((c) => c.name === attributes[1].value)) {
        throw new Error(`${name}: unreviewed MDX component, HTML, or attributes`);
      }
    } else if (!markdownNodes.has(node.type)) {
      throw new Error(`${name}: unreviewed MDX node ${node.type}`);
    }
    if (['link', 'image', 'definition'].includes(node.type)) checkDestination(name, node.url, files);
    for (const child of node.children ?? []) visit(child);
  }
  visit(tree);
  return tree;
}

export function checkJSONReferences(name, content, files) {
  function visit(value, key = '') {
    if (Array.isArray(value)) value.forEach((v) => visit(v, key));
    else if (value && typeof value === 'object') Object.entries(value).forEach(([k, v]) => visit(v, k.toLowerCase()));
    else if (typeof value === 'string') {
      checkTextURLs(name, value, files);
      for (const link of value.matchAll(/\]\(([^)]+)\)/g)) checkDestination(name, link[1], files);
      if (key === 'file') {
        if (value.startsWith('/') || value.split('/').some((part) => !part || part === '.' || part === '..') || !value.endsWith('.go') || !declarationPackages.has(posix.dirname(value))) throw new Error(`${name}: invalid source location`);
        checkDestination(name, `https://echo.labstack.com/pro/${value}`, files);
      }
      else if (['path', 'url', 'href', 'src', 'source'].includes(key) || key === 'type' && /^[a-z][a-z\d+.-]*:/i.test(value)) checkDestination(name, value, files);
    }
  }
  visit(JSON.parse(content));
}

function checkTextURLs(name, content, files) {
  for (const match of content.matchAll(/(?:https?:\/\/|www\.)[^\s<>"`]+/gi)) {
    let target = match[0].replace(/[),.;:!?]+$/, '');
    if (/^www\./i.test(target)) target = `https://${target}`;
    checkDestination(name, target, files);
  }
}
